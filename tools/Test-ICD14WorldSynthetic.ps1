<#
.SYNOPSIS
    icd14 agent C: the crime ledger, the area snapshot and the switches (kdcmp.lua KCD2MP.icd14).
    No game, relay or agent needed.
.DESCRIPTION
    Same driver as Test-NpcSmoothSynthetic.ps1 (the real kdcmp.lua under
    MoonSharp, engine stubbed, fake clock); scenario file
    Test-ICD14WorldSynthetic.lua. Live evidence: none yet (needs a two-player test).
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Test-ICD14WorldSynthetic.ps1
#>
[CmdletBinding()]
param(
    [string] $KdcmpLua = '',
    [string] $MoonSharpVersion = '2.0.0.0'
)
$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Path
& (Join-Path $toolsDir 'Test-NpcSmoothSynthetic.ps1') `
    -KdcmpLua $KdcmpLua -MoonSharpVersion $MoonSharpVersion `
    -Scenario (Join-Path $toolsDir 'Test-ICD14WorldSynthetic.lua') `
    -Title 'icd14 world synthetic Lua test'
exit $LASTEXITCODE
